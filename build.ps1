[CmdletBinding()]
param(
    [ValidateSet("Release", "Debug")]
    [string]$Configuration = "Release",
    [string]$CompilerPath = "",
    [string]$Output = "",
    [switch]$ExportOnly
)

$ErrorActionPreference = "Stop"
$utf8 = New-Object System.Text.UTF8Encoding($false)
$OutputEncoding = $utf8
try { [Console]::OutputEncoding = $utf8 } catch { }
$root = $PSScriptRoot
if (-not $root) { $root = (Get-Location).Path }

function Find-Csc {
    param([string]$Explicit)

    if ($Explicit) {
        if (Test-Path -LiteralPath $Explicit) {
            return (Resolve-Path -LiteralPath $Explicit).Path
        }
        throw "CompilerPath not found: $Explicit"
    }

    if ($env:CSC) {
        if (Test-Path -LiteralPath $env:CSC) {
            return $env:CSC
        }
        throw "CSC points to a missing file: $($env:CSC)"
    }

    $command = Get-Command csc.exe -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }

    $windows = $env:WINDIR
    if (-not $windows) {
        $windows = [Environment]::GetFolderPath("Windows")
    }

    $candidates = New-Object System.Collections.Generic.List[string]
    foreach ($arch in @("Framework64", "Framework")) {
        $base = Join-Path $windows ("Microsoft.NET\" + $arch)
        if (-not (Test-Path -LiteralPath $base)) { continue }
        $dirs = Get-ChildItem -LiteralPath $base -Directory -Filter "v4.*" -ErrorAction SilentlyContinue |
            Sort-Object Name -Descending
        foreach ($dir in $dirs) {
            $csc = Join-Path $dir.FullName "csc.exe"
            if (Test-Path -LiteralPath $csc) { [void]$candidates.Add($csc) }
        }
    }

    if ($candidates.Count -gt 0) { return $candidates[0] }
    throw "Could not find a .NET Framework 4.x csc.exe. Enable .NET Framework 4.x, or set -CompilerPath / CSC."
}

if ([string]::IsNullOrWhiteSpace($Output)) {
    if ($Configuration -eq "Debug") { $Output = "QuotaFloat.debug.exe" } else { $Output = "QuotaFloat.exe" }
}

$singleName = "QuotaFloat.single.cs"
$assemblyName = "AssemblyInfo.cs"
$singleSource = Join-Path $root $singleName
$sourceFiles = @(
    Get-ChildItem -LiteralPath $root -Filter "*.cs" -File -Recurse |
        Where-Object { $_.FullName -notmatch "[\\/](bin|obj)[\\/]" } |
        Where-Object { $_.Name -ne $singleName } |
        Sort-Object FullName
)
if ($sourceFiles.Count -eq 0) { throw "No .cs source files found." }

$sections = New-Object 'System.Collections.Generic.List[string]'
$assemblyContent = ""
foreach ($file in $sourceFiles) {
    $text = [System.IO.File]::ReadAllText($file.FullName, [System.Text.Encoding]::UTF8)
    $fileUsings = New-Object 'System.Collections.Generic.List[string]'
    $body = New-Object System.Text.StringBuilder
    foreach ($line in ($text -split "\r?\n")) {
        $trimmed = $line.Trim()
        if ($trimmed -match '^using\s+[A-Za-z0-9_.]+\s*;$') {
            [void]$fileUsings.Add($trimmed)
            continue
        }
        [void]$body.AppendLine($line.TrimEnd())
    }
    $content = $body.ToString().Trim()
    if ($content.Length -gt 0 -and $file.Name -eq $assemblyName) {
        $assemblyContent = $content
        continue
    }
    if ($content.Length -gt 0) {
        if ($fileUsings.Count -gt 0) {
            $namespaceIndex = $content.IndexOf("namespace QuotaFloat")
            $braceIndex = -1
            if ($namespaceIndex -ge 0) {
                $braceIndex = $content.IndexOf("{", $namespaceIndex)
            }
            if ($braceIndex -ge 0) {
                $usingLines = @($fileUsings | ForEach-Object { "    " + $_ })
                $content = $content.Insert($braceIndex + 1,
                    "`r`n" + ($usingLines -join "`r`n"))
            }
        }
        [void]$sections.Add("// ---- source: " + $file.Name + " ----")
        [void]$sections.Add($content)
        [void]$sections.Add("")
    }
}
if ($sections.Count -eq 0) { throw "No content exported from source files." }

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine("// <auto-generated>")
[void]$builder.AppendLine("// Generated by build.ps1 from the split C# sources.")
[void]$builder.AppendLine("// Edit the split sources, not this file.")
[void]$builder.AppendLine("// </auto-generated>")
[void]$builder.AppendLine()
if ($assemblyContent.Length -gt 0) {
    [void]$builder.AppendLine("// ---- source: AssemblyInfo.cs ----")
    [void]$builder.AppendLine($assemblyContent)
    [void]$builder.AppendLine()
}
foreach ($section in $sections) {
    [void]$builder.AppendLine($section)
}
$generated = $builder.ToString().TrimEnd() + "`r`n"
[System.IO.File]::WriteAllText($singleSource, $generated,
    (New-Object System.Text.UTF8Encoding($true)))

$singleInfo = Get-Item -LiteralPath $singleSource
Write-Host ("Single source: {0} ({1} files, {2:N0} bytes)" -f
    $singleInfo.FullName, $sourceFiles.Count, $singleInfo.Length)
if ($ExportOnly) { exit 0 }

$csc = Find-Csc $CompilerPath
$manifest = Join-Path $root "app.manifest"
$icon = Join-Path $root "app.ico"
if (-not (Test-Path -LiteralPath $manifest)) { throw "Missing app.manifest: $manifest" }
if (-not (Test-Path -LiteralPath $icon)) { throw "Missing app.ico: $icon" }

if ([System.IO.Path]::IsPathRooted($Output)) {
    $outPath = $Output
} else {
    $outPath = Join-Path $root $Output
}

$common = @(
    "-nologo",
    "-codepage:65001",
    "-utf8output",
    "-win32manifest:$manifest",
    "-win32icon:$icon",
    "-out:$outPath",
    "-reference:System.dll",
    "-reference:System.Core.dll",
    "-reference:System.Drawing.dll",
    "-reference:System.Windows.Forms.dll",
    "-reference:System.Web.Extensions.dll",
    "-reference:System.Security.dll"
)

if ($Configuration -eq "Debug") {
    $cscArgs = @("-target:exe", "-optimize-", "-debug:full", "-define:DEBUG") +
        $common + @($singleSource)
} else {
    $cscArgs = @("-target:winexe", "-optimize+", "-debug-") +
        $common + @($singleSource)
}

Write-Host "Compiler     : $csc"
Write-Host "Configuration: $Configuration"
Write-Host "Sources      : $($sourceFiles.Count) split -> 1 single"

& $csc @cscArgs
if ($LASTEXITCODE -ne 0) {
    Write-Host "Build failed. If QuotaFloat.exe is running, close it and retry." -ForegroundColor Yellow
    exit $LASTEXITCODE
}

$file = Get-Item -LiteralPath $outPath
Write-Host ("Output       : {0} ({1:N0} bytes)" -f $file.FullName, $file.Length)
$pdb = [System.IO.Path]::ChangeExtension($outPath, ".pdb")
if (Test-Path -LiteralPath $pdb) {
    $pdbFile = Get-Item -LiteralPath $pdb
    Write-Host ("Symbols      : {0} ({1:N0} bytes)" -f $pdbFile.FullName, $pdbFile.Length)
}
exit 0
